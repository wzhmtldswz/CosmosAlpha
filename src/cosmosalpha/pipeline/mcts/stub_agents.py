"""Stub agents for MCTS mode — skip LLM calls for Hypothesis & Feedback.

In MCTS, the Alpha Portrait already encodes the research idea and the
multi-dimensional scoring / backpropagation serves as feedback.
Running full LLM-based HypothesisAgent and FeedbackAgent per round is
redundant, adding ~40% runtime with no quality gain for MCTS search.

These stubs produce structurally valid domain objects without any LLM call.
"""

from __future__ import annotations

from datetime import UTC, datetime

from cosmosalpha.agents.protocol import (
    FeedbackRequest,
    HypothesisVerdict,
    ObjectRef,
    ResearchContext,
    ResearchFeedback,
    ResearchHypothesis,
)
from cosmosalpha.core import stable_sha256


def _now_iso() -> str:
    return datetime.now(UTC).isoformat()


class MCTSHypothesisStub:
    """No-LLM hypothesis: construct minimal ResearchHypothesis from context."""

    def propose(
        self,
        context: ResearchContext,
        *,
        field_catalog_ref: ObjectRef,
        history_lesson_refs: tuple[ObjectRef, ...] = (),
    ) -> ResearchHypothesis:
        """Carry MCTS guidance and current Catalog references into the hypothesis."""
        context_sections: list[str] = []
        if context.constraints:
            context_sections.append(
                "MCTS constraints:\n" + "\n".join(context.constraints)
            )
        if context.history_summaries:
            context_sections.append(
                "MCTS history:\n" + "\n".join(context.history_summaries)
            )
        context_text = "\n".join(context_sections) or "MCTS refinement"
        hid = stable_sha256({"context": context_text, "ts": _now_iso()})
        return ResearchHypothesis(
            hypothesis_id=f"mcts-h-{hid[:16]}",
            statement=f"MCTS-guided factor refinement: {context_text}",
            rationale=(
                "Auto-generated by MCTS search context; formal hypothesis agent "
                "bypassed."
            ),
            mechanism="MCTS UCT-guided exploration with multi-dimensional scoring.",
            testable_prediction="Factor will show improvement in the target dimension.",
            expected_direction=(
                "positive" if "effectiveness" in context_text.lower() else "any"
            ),
            required_fields=tuple(context.available_fields),
            prediction_horizon=context.frequency,
            assumptions=(),
            source_refs=(
                (context.operator_catalog_ref,)
                + (field_catalog_ref,)
                + history_lesson_refs
            ),
            schema_version="research-hypothesis/1.0",
        )


class MCTSFeedbackStub:
    """No-LLM feedback: return a minimal neutral ResearchFeedback.

    evidence_refs are computed from the FeedbackRequest to satisfy the
    ExperimentLessonBuilder validation contract.
    """

    def generate(self, request: FeedbackRequest, *, cycle_id: str) -> ResearchFeedback:
        """Return neutral feedback carrying every current evidence reference."""
        evidence = (
            (request.hypothesis_ref,)
            + request.factor_design_refs
            + request.factor_proposal_refs
            + request.factor_refs
            + request.validation_report_refs
            + request.calculation_result_refs
            + request.factor_preprocessing_result_refs
            + request.evaluation_result_refs
            + request.acceptance_decision_refs
            + request.comparison_baseline_refs
        )
        fid = stable_sha256({"cycle_id": cycle_id, "ts": _now_iso()})
        return ResearchFeedback(
            feedback_id=f"mcts-fb-{fid[:16]}",
            cycle_id=cycle_id,
            hypothesis_verdict=HypothesisVerdict.INCONCLUSIVE,
            summary="MCTS mode: feedback agent bypassed. Evaluation via multi-dimensional scoring.",
            supported_findings=(),
            rejected_findings=(),
            failure_analysis=(),
            next_actions=(),
            next_hypothesis_hint=None,
            evidence_refs=evidence,
            schema_version="research-feedback/2.0",
        )
